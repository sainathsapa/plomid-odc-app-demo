"""Per-video seat mapping tests — analyse-then-map, candidate-grade."""

from __future__ import annotations

from odc.autolayout import (
    _capacity_constrained_rows,
    _group_peaks_into_rows,
    _pick_peaks,
    _polygon_for_peak,
    propose_seat_layout,
)


def test_pick_peaks_separated_hotspots():
    heat = [[0.0] * 12 for _ in range(12)]
    heat[2][2] = 10.0
    heat[8][9] = 8.0
    heat[2][3] = 9.0  # neighbor of the max: suppressed by separation
    assert _pick_peaks(heat) == [(2, 2), (9, 8)]
    assert _pick_peaks([[0.0] * 12 for _ in range(12)]) == []
    weak = [[0.0] * 12 for _ in range(12)]
    weak[5][5] = 1.0
    assert _pick_peaks(weak, min_frac=0.3) == [(5, 5)]
    assert _pick_peaks(weak, min_frac=1.1) == []


def test_polygon_stays_in_frame():
    poly = _polygon_for_peak(0, 0, {})
    assert len(poly) == 4
    assert all(0.0 <= x <= 1.0 and 0.0 <= y <= 1.0 for x, y in poly)
    big = _polygon_for_peak(6, 6, {(6, 6): [(0.9, 0.9)] * 5})
    xs = [x for x, _ in big]
    assert max(xs) - min(xs) >= 0.12 and max(xs) <= 1.0


def test_auto_peaks_become_explicit_front_to_rear_rows():
    rows = _group_peaks_into_rows([(9, 8), (2, 2), (6, 8), (2, 5), (9, 5)])
    assert rows == [[(2, 2)], [(2, 5), (9, 5)], [(6, 8), (9, 8)]]


def test_auto_layout_preserves_single_seat_bus_rows():
    peaks = [(6, 1), (6, 5), (6, 9)]
    rows = _capacity_constrained_rows(peaks, {})
    assert rows == [[(6, 1)], [(6, 5)], [(6, 9)]]


def test_auto_layout_allows_one_seat_cabin_row():
    assert _capacity_constrained_rows([(6, 5)], {}) == [[(6, 5)]]


def test_auto_layout_caps_front_row_at_two_when_clustering_finds_three():
    rows = _capacity_constrained_rows(
        [(1, 1), (3, 1), (5, 1), (2, 4), (4, 4)], {}
    )
    assert [len(row) for row in rows] == [2, 3]


def test_probe_empty_cabin_proposes_nothing():
    # E1: parked empty cabin, no sustained persons -> None (uncalibrated),
    # never invented seats. Small probe budget keeps the test fast.
    res = propose_seat_layout("footage/E1_empty_cabin.mp4", max_probe_frames=6)
    assert res.layout is None
    assert res.frames_probed > 0
    assert "no sustained" in res.reason


def test_probe_crowded_van_proposes_seats():
    res = propose_seat_layout("footage/R1_rear_wide.mp4", max_probe_frames=8)
    assert res.layout is not None
    assert res.layout.version == "auto-v1"
    assert 1 <= len(res.layout.seats) <= 6
    assert all(s.seat_id.startswith("seat_") for s in res.layout.seats)
    # Seat identifiers remain generic; classification is never derived from
    # names generated by an automatic layout.
    assert all("child" not in s.seat_id.lower() for s in res.layout.seats)


def test_probe_missing_file_never_raises():
    res = propose_seat_layout("footage/does-not-exist.mp4")
    assert res.layout is None
    assert res.reason == "missing file"
